from datetime import datetime, timezone
from typing import List, Literal, Optional
from pydantic import BaseModel, Field, field_validator


class ChatMessage(BaseModel):
    """Single message within a conversational session."""
    role: Literal["user", "assistant", "system"] = Field(..., description="Message author role", examples=["user"])
    content: str = Field(..., min_length=1, max_length=15000, description="Message text content")
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc), description="Timestamp of the message")

    model_config = {
        "json_schema_extra": {
            "example": {
                "role": "user",
                "content": "I feel stressed about my upcoming exams.",
                "timestamp": "2026-11-02T12:00:00Z",
            }
        }
    }


class ChatSessionInDB(BaseModel):
    """Chat session document representation stored in MongoDB 'chat_sessions' collection."""
    id: Optional[str] = Field(default=None, alias="_id", description="MongoDB ObjectId as string")
    user_id: str = Field(..., description="Reference to the owning user's _id", examples=["6725ea9478f691bdf1012345"])
    title: str = Field(default="New Conversation", max_length=200, description="Conversation session title")
    messages: List[ChatMessage] = Field(default_factory=list, description="Ordered list of conversation messages")
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc), description="Session creation timestamp")
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc), description="Last interaction timestamp")

    model_config = {
        "populate_by_name": True,
        "json_schema_extra": {
            "example": {
                "_id": "6725ea9478f691bdf1077777",
                "user_id": "6725ea9478f691bdf1012345",
                "title": "Exam Stress Support",
                "messages": [
                    {
                        "role": "assistant",
                        "content": "Hi! I am your MentalWell wellness companion.",
                        "timestamp": "2026-11-02T12:00:00Z",
                    },
                    {
                        "role": "user",
                        "content": "I feel stressed about my upcoming exams.",
                        "timestamp": "2026-11-02T12:01:00Z",
                    },
                ],
                "created_at": "2026-11-02T12:00:00Z",
                "updated_at": "2026-11-02T12:01:00Z",
            }
        },
    }


class SendMessageRequest(BaseModel):
    """Request payload to send a message to the AI Wellness Assistant."""
    message: str = Field(
        ...,
        min_length=1,
        max_length=5000,
        description="User text message (1 to 5000 characters).",
        examples=["I've been feeling overwhelmed with my study schedule lately."],
    )
    session_id: Optional[str] = Field(
        default=None,
        description="Optional session ID to continue an existing conversation. If omitted, a new session is created.",
        examples=["6725ea9478f691bdf1077777"],
    )

    @field_validator("message")
    @classmethod
    def validate_message_not_empty(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Message cannot be empty or purely whitespace.")
        return stripped


class SendMessageResponse(BaseModel):
    """Response returned after processing a user message and generating an AI reply."""
    session_id: str = Field(..., description="Unique ID of the chat session")
    title: str = Field(..., description="Conversation title")
    user_message: ChatMessage = Field(..., description="Echoed user message with timestamp")
    assistant_message: ChatMessage = Field(..., description="Assistant reply generated by Gemini AI")
    created_at: datetime = Field(..., description="Session creation timestamp")
    updated_at: datetime = Field(..., description="Session last updated timestamp")


class ChatSessionSummaryResponse(BaseModel):
    """Brief summary of a chat session for sidebar listing."""
    id: str = Field(..., description="Session ObjectId as string")
    title: str = Field(..., description="Conversation title")
    message_count: int = Field(..., description="Total number of messages in the session")
    last_message: Optional[str] = Field(default=None, description="Preview snippet of the last message")
    created_at: datetime = Field(..., description="Session creation timestamp")
    updated_at: datetime = Field(..., description="Session last updated timestamp")


class ChatSessionDetailResponse(BaseModel):
    """Detailed chat session including complete message history."""
    id: str = Field(..., description="Session ObjectId as string")
    title: str = Field(..., description="Conversation title")
    messages: List[ChatMessage] = Field(default_factory=list, description="All messages in chronological order")
    created_at: datetime = Field(..., description="Session creation timestamp")
    updated_at: datetime = Field(..., description="Session last updated timestamp")


class ChatSessionsListResponse(BaseModel):
    """Paginated list of chat sessions."""
    sessions: List[ChatSessionSummaryResponse] = Field(default_factory=list, description="List of user chat sessions")
    total: int = Field(..., description="Total number of sessions owned by the user")
    limit: int = Field(default=20, description="Page limit applied")
    offset: int = Field(default=0, description="Page offset applied")


class DeleteSessionResponse(BaseModel):
    """Response returned upon successful deletion of a chat session."""
    message: str = Field(default="Session deleted successfully")
    id: str = Field(..., description="Deleted session ID")
